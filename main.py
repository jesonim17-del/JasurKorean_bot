def get_menu():
    markup = types.InlineKeyboardMarkup()
    markup.add(
        types.InlineKeyboardButton(
            "📚 Учить случайное слово", callback_data="learn"
        )
    )
    markup.add(
        types.InlineKeyboardButton("🎮 Викторина (Тест)", callback_data="quiz")
    )
    markup.add(
        types.InlineKeyboardButton(
            "📊 Всего слов в базе", callback_data="stats"
        )
    )
    return markup


@bot.message_handler(commands=["start"])
def send_welcome(message):
    bot.send_message(
        message.chat.id,
        f"Привет! 👋 Я твой личный бот для изучения корейских слов.\n"
        f"В моей базе уже **{len(WORDS)} слов**.\n\nВыбирай режим:",
        reply_markup=get_menu(),
        parse_mode="Markdown",
    )


@bot.callback_query_handler(func=lambda call: True)
def callback_inline(call):
    if call.data == "stats":
        bot.answer_callback_query(call.id)
        bot.edit_message_text(
            f"📊 Всего слов в памяти бота: {len(WORDS)}",
            call.message.chat.id,
            call.message.message_id,
            reply_markup=get_menu(),
        )

    elif call.data == "learn":
        word = random.choice(WORDS)
        markup = types.InlineKeyboardMarkup()
        markup.add(
            types.InlineKeyboardButton(
                "👁 Показать перевод", callback_data=f"show_{word['kr']}"
            )
        )
        markup.add(
            types.InlineKeyboardButton(
                "🔄 Следующее слово", callback_data="learn"
            )
        )
        markup.add(types.InlineKeyboardButton("🏠 В меню", callback_data="menu"))
        bot.edit_message_text(
            f"🇰🇷 Корейское слово:\n\n<b>{word['kr']}</b>",
            call.message.chat.id,
            call.message.message_id,
            reply_markup=markup,
            parse_mode="HTML",
        )

    elif call.data.startswith("show_"):
        kr_word = call.data.replace("show_", "")
        ru_translation = next(
            (w["ru"] for w in WORDS if w["kr"] == kr_word), "Перевод не найден"
        )
        markup = types.InlineKeyboardMarkup()
        markup.add(
            types.InlineKeyboardButton(
                "🔄 Следующее слово", callback_data="learn"
            )
        )
        markup.add(types.InlineKeyboardButton("🏠 В меню", callback_data="menu"))
        bot.edit_message_text(
            f"🇰🇷 Корейское слово:\n<b>{kr_word}</b>\n\n🇷🇺 Перевод:\n<b>{ru_translation}</b>",
            call.message.chat.id,
            call.message.message_id,
            reply_markup=markup,
            parse_mode="HTML",
        )

    elif call.data == "menu":
        bot.edit_message_text(
            "Главное меню:",
            call.message.chat.id,
            call.message.message_id,
            reply_markup=get_menu(),
        )

    elif call.data == "quiz":
        correct = random.choice(WORDS)
        wrongs = random.sample(
            [w for w in WORDS if w["kr"] != correct["kr"]], 3
        )
        options = wrongs + [correct]
        random.shuffle(options)

        markup = types.InlineKeyboardMarkup()
        for opt in options:
            is_corr = "1" if opt["kr"] == correct["kr"] else "0"
            markup.add(
                types.InlineKeyboardButton(
                    opt["ru"], callback_data=f"ans_{is_corr}"
                )
            )
        markup.add(types.InlineKeyboardButton("🏠 В меню", callback_data="menu"))

        bot.edit_message_text(
            f"❓ Как переводится слово:\n\n<b>{correct['kr']}</b>?",
            call.message.chat.id,
            call.message.message_id,
            reply_markup=markup,
            parse_mode="HTML",
        )

    elif call.data.startswith("ans_"):
        status = call.data.split("_")[1]
        if status == "1":
            text = "✅ **Правильно! Отличная работа!** 🎉"
        else:
            text = "❌ **Неправильно.** Попробуй ещё раз!"

        markup = types.InlineKeyboardMarkup()
        markup.add(
            types.InlineKeyboardButton(
                "🎮 Ещё вопрос", callback_data="quiz"
            )
        )
        markup.add(types.InlineKeyboardButton("🏠 В меню", callback_data="menu"))
        bot.edit_message_text(
            text,
            call.message.chat.id,
            call.message.message_id,
            reply_markup=markup,
            parse_mode="Markdown",
        )


